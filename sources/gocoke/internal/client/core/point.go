package core

// Point represents a 2D integer point
type Point struct {
	X int
	Y int
}

// Point2D represents a 2D float point
type Point2D struct {
	X float64
	Y float64
}

// Rect represents a rectangle with float coordinates
type Rect struct {
	X      float64
	Y      float64
	Width  float64
	Height float64
}

// Vector2D represents a 2D vector
type Vector2D struct {
	X float64
	Y float64
}
